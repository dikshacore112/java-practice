public class student {
    
        String name;
        int age;
        String course;
public static void main(String[] args) {
    student s1=new student();
    s1.name="Diksha";
    s1.age=20;
    s1.course="BCA";
    System.out.println("Name: "+s1.name);
    System.out.println("Age: "+s1.age);
    System.out.println("Course: "+s1.course);
}
}